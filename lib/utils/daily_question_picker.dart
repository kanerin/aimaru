/// 出題しうる全質問（重複なし）。
List<String> get allDailyQuestions =>
    [...dailyQuestions, ..._extraQuestions, ..._reserveQuestions];

/// [date] から決定的に質問を1つ選ぶ。
/// 質問をFirestoreに保存していなかった頃の選び方で、保存前の履歴の復元と、
/// [pickUnaskedQuestion]の第一候補（古い版のアプリを使う相手と揃えるため）に使う。
String pickDailyQuestion(DateTime date) {
  // 夏時間などで日数がずれないよう、年月日だけをUTCにして数える。
  final day = DateTime.utc(date.year, date.month, date.day);
  if (day.isBefore(_extraQuestionsStart)) {
    final startOfYear = DateTime(date.year, 1, 1);
    final dayOfYear = date.difference(startOfYear).inDays;
    return dailyQuestions[dayOfYear % dailyQuestions.length];
  }
  final n = day.difference(_extraQuestionsStart).inDays;
  if (n < _extraQuestions.length) return _extraQuestions[n];
  // 追加分を出し切った後は全問を通しで回す（年をまたいでも途切れない）。
  final all = [...dailyQuestions, ..._extraQuestions];
  return all[(n - _extraQuestions.length) % all.length];
}

/// そのカップルにまだ出していない質問から、[date]の質問を1つ選ぶ。
///
/// [askedOn]は「質問文 → 最後に出した日付キー('yyyy-MM-dd')」。
/// 第一候補は[pickDailyQuestion]で、まだ出していなければそれを返す
/// （質問を保存しない古い版のアプリを使う相手とも同じ質問になる）。
/// 出題済みなら表を順に送って未出題のものを探し、全問を出し切った後は
/// いちばん長く出していない質問に戻る。
String pickUnaskedQuestion(DateTime date, Map<String, String> askedOn) {
  final all = allDailyQuestions;
  final preferred = pickDailyQuestion(date);
  if (!askedOn.containsKey(preferred)) return preferred;

  final start = all.indexOf(preferred);
  String? oldest;
  for (var i = 1; i <= all.length; i++) {
    final candidate = all[(start + i) % all.length];
    final lastAsked = askedOn[candidate];
    if (lastAsked == null) return candidate;
    if (oldest == null || lastAsked.compareTo(askedOn[oldest]!) < 0) {
      oldest = candidate;
    }
  }
  return oldest!;
}

/// 'yyyy-MM-dd' 形式の日付キーから、その日に出ていた質問を返す。
/// 質問をFirestoreに保存する前の回答は日付キーしか持たないため、そこから
/// 質問文を復元するのに使う。解釈できないキーの場合はnullを返す。
String? questionForDateKey(String dateKey) {
  final date = DateTime.tryParse(dateKey);
  if (date == null) return null;
  return pickDailyQuestion(date);
}

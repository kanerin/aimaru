/// [date] から決定的に質問を1つ選ぶ。
/// 同じ日なら2人とも同じ質問を見られるよう、乱数やFirestoreの状態は使わない。
String pickDailyQuestion(DateTime date) {
  // 夏時間などで日数がずれないよう、年月日だけをUTCにして数える。
  final day = DateTime.utc(date.year, date.month, date.day);
  if (day.isBefore(_extraQuestionsStart)) {
    final startOfYear = DateTime(date.year, 1, 1);
    final dayOfYear = date.difference(startOfYear).inDays;
    return dailyQuestions[dayOfYear % dailyQuestions.length];
  }
  final n = day.difference(_extraQuestionsStart).inDays;
  if (n < _extraQuestions.length) return _extraQuestions[n];
  // 追加分を出し切った後は全問を通しで回す（年をまたいでも途切れない）。
  final all = [...dailyQuestions, ..._extraQuestions];
  return all[(n - _extraQuestions.length) % all.length];
}

/// 'yyyy-MM-dd' 形式の日付キーから、その日に出ていた質問を返す。
/// 過去の回答一覧（履歴）は日付キーしか持たないため、そこから質問文を
/// 復元するのに使う（質問はサーバーに保存せず日付から決定的に選ぶ設計）。
/// 解釈できないキーの場合はnullを返す。
String? questionForDateKey(String dateKey) {
  final date = DateTime.tryParse(dateKey);
  if (date == null) return null;
  return pickDailyQuestion(date);
}
